/** The dictionaries shipped with the library, by language (the part before any `-`). */
export const DICTIONARIES: Record<string, Dictionary> = { fr: FR, en: EN };

/** The texts for a course: its language's dictionary (French by default), then its overrides. */
export function labelsFor(lang = 'fr', over?: Partial<Record<string, string>>): LabelSet {
  const base = DICTIONARIES[lang.split('-')[0]] ?? FR;
  return { ...base, ...(over ?? {}), lang } as LabelSet;
}

/** Does `n` call for a plural in this language? French: 2 and more; others: anything but 1. */
export const isPlural = (n: number, lang: string): boolean => (lang.startsWith('fr') ? Math.abs(n) >= 2 : Math.abs(n) !== 1);

/** A text with its placeholders filled: `{x}` → the value, `{s:x}` → the plural mark when x calls for one. */
export function tr(L: LabelSet, key: LabelKey, vars: Record<string, string | number> = {}): string {
  return L[key].replace(/\{(?:(s):)?(\w+)\}/g, (m, s: string | undefined, name: string) => {
    const v = vars[name];
    if (v == null) return m;
    return s ? (isPlural(Number(v), L.lang) ? 's' : '') : String(v);
  });
}
